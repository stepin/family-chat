/**
 * The shape every catalogue has: the keys of `ru` with plain `string` in
 * place of literal types (a function returning one of two Russian words
 * returns `string` for English).
 */
type Widen<T> = T extends (...args: infer A) => string
  ? (...args: A) => string
  : T extends string
    ? string
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

export type Strings = Widen<typeof ru>;

